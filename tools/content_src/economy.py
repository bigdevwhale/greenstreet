def crop_rows():
    rows = []
    for (key, place, sow, days, regrow, yld, price, art, ramp, unlock, vru, ven, aru, aen) in CROPS:
        sp = crop_of(key)
        sru, sen = SPECIES[sp]
        rows.append([key, sp, place, sow, days, tends_for(days), regrow, yld, price, art, ramp, unlock,
                     f"{sru} «{vru}»", f"{sen} '{ven}'", aru, aen])
    return rows


