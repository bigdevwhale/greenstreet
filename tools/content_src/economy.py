MARKUP = {"kitchen": 1.35, "oven": 1.4, "workbench": 1.4, "cellar": 1.5, "hive": 1.5}
GROUPS = {
    "anyfish": [g[0] for g in GOODS if g[1] == "fish"],
    "anymush": "chanterelle boletus suillus honey_fungus porcini russula morel".split(),
    "anyberry": "strawberry raspberry currant gooseberry honeysuckle wild_strawberry wild_raspberry rowan rosehip elderberry sea_buckthorn bird_cherry".split(),
    "anyflower": "chamomile calendula cornflower nasturtium marigold sweetpea aster cosmos tulip daffodil crocus lavender hyacinth amaryllis".split(),
    "anyherb": "dill parsley coriander mint basil thyme valerian catnip sorrel".split(),
    "anyveg": "radish lettuce spinach onion carrot beet potato cabbage zucchini tomato".split(),
}


def _base_values():
    """Worth of raw things: a variety its price, a species the mean of its varieties, goods their price."""
    val, by_sp = {}, {}
    for r in CROPS:
        val[r[0]] = r[6]
        by_sp.setdefault(crop_of(r[0]), []).append(r[6])
    for sp, ps in by_sp.items():
        val[sp] = sum(ps) / len(ps)
    for g in GOODS:
        val[g[0]] = g[6]
    for g, ks in GROUPS.items():
        ps = sorted(val[k] for k in ks)
        val[g] = ps[len(ps) // 2]  # median: a cook uses whatever is cheap at hand
    return val


def _cost(needs, val):
    return sum(val[k] * int(q) for k, q in (p.split(":") for p in needs.split(",")))


def product_prices():
    """Fair price of each product: at least the written floor, and at least ingredients x markup / qty
    for every recipe that makes it (so no recipe loses money). Iterated because products feed products."""
    val = _base_values()
    price = {}
    for r in RECIPES:
        price[r[2]] = max(price.get(r[2], 0), r[6])
    for _ in range(6):
        val.update(price)
        for r in RECIPES:
            need = -(-_cost(r[1], val) * MARKUP[r[4]] // r[3])
            price[r[2]] = max(price[r[2]], int(need))
    return price


def report():
    price = product_prices()
    val = _base_values()
    val.update(price)
    for r in RECIPES:
        cost = _cost(r[1], val)
        worth = r[3] * price[r[2]]
        print(f"{r[0]:28} cost {cost:6.1f}  sells {r[3]} x {price[r[2]]:3} = {worth:4}  x{worth / cost:4.2f}")


def main():
    price = product_prices()
    write("crops.tsv", CROP_COLS, crop_rows())
    write("goods.tsv", GOOD_COLS, [list(g) for g in GOODS])
    write("recipes.tsv", REC_COLS, [[*r[:6], price[r[2]], *r[7:]] for r in RECIPES])


if __name__ == "__main__":
    main()
    report()
    print(len(CROPS), "crops,", len(GOODS), "goods,", len(RECIPES), "recipes")
