def crop_of(key):
    best = ""
    for s in SPECIES:
        if key.startswith(s + "_") and len(s) > len(best):
            best = s
    return best


def tends_for(days):
    """40–60 % of days: short crops need a little more care, long ones a little less."""
    if days <= 30:
        f = 0.6
    elif days <= 90:
        f = 0.5
    elif days <= 150:
        f = 0.45
    else:
        f = 0.4
    return max(1, round(days * f))


